CREATE TABLE IF NOT EXISTS t_sys_user (
  id BIGINT NOT NULL AUTO_INCREMENT,
  user_name VARCHAR(50) NOT NULL,
  account_name VARCHAR(50) NOT NULL,
  pwd VARCHAR(200),
  locked INT NOT NULL DEFAULT 0,
  account_type INT DEFAULT 1,
  create_user_id BIGINT NOT NULL DEFAULT -1,
  description VARCHAR(200),
  create_time DATETIME,
  account_port_type BIGINT DEFAULT 1,
  chrid VARCHAR(20) DEFAULT '0',
  chrid_type VARCHAR(2500),
  org_id BIGINT,
  url VARCHAR(2000),
  PRIMARY KEY (id)
);
CREATE TABLE IF NOT EXISTS t_sys_role (
  id BIGINT NOT NULL AUTO_INCREMENT, name VARCHAR(50) NOT NULL, user_id BIGINT NOT NULL DEFAULT -1,
  description VARCHAR(200), create_time DATETIME, PRIMARY KEY (id));
CREATE TABLE IF NOT EXISTS t_sys_resources (
  id BIGINT NOT NULL AUTO_INCREMENT, name VARCHAR(50) NOT NULL, parent_id BIGINT NOT NULL DEFAULT 0,
  res_key VARCHAR(50), type VARCHAR(20) DEFAULT '0', res_url VARCHAR(200), order_no INT NOT NULL DEFAULT 0,
  icon VARCHAR(100), btn VARCHAR(200), is_hide INT NOT NULL DEFAULT 0, description VARCHAR(200),
  PRIMARY KEY (id));
CREATE TABLE IF NOT EXISTS t_sys_user_role (id BIGINT NOT NULL AUTO_INCREMENT, user_id BIGINT NOT NULL, role_id BIGINT NOT NULL, PRIMARY KEY (id));
CREATE TABLE IF NOT EXISTS t_sys_role_action (id BIGINT NOT NULL AUTO_INCREMENT, res_id BIGINT NOT NULL, role_id BIGINT NOT NULL, PRIMARY KEY (id));
CREATE TABLE IF NOT EXISTS t_sys_user_action (res_id BIGINT NOT NULL, user_id BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS t_sys_dictionary (
  id BIGINT NOT NULL AUTO_INCREMENT, dict_code VARCHAR(50) NOT NULL, dict_name VARCHAR(100) NOT NULL,
  description VARCHAR(200), create_time DATETIME, PRIMARY KEY (id));
CREATE TABLE IF NOT EXISTS t_sys_dictionary_detail (
  id BIGINT NOT NULL AUTO_INCREMENT, dict_code VARCHAR(50) NOT NULL, item_key VARCHAR(50) NOT NULL,
  item_value VARCHAR(200), order_no INT DEFAULT 0, description VARCHAR(200), PRIMARY KEY (id));
CREATE TABLE IF NOT EXISTS t_org_info (
  id BIGINT NOT NULL AUTO_INCREMENT, org_code VARCHAR(50) NOT NULL, org_name VARCHAR(200) NOT NULL,
  parent_id BIGINT DEFAULT 0, org_type VARCHAR(20) DEFAULT '1', description VARCHAR(200),
  create_time DATETIME, PRIMARY KEY (id));

